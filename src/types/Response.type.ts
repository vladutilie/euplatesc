import { Currency } from './Hmac.type';

/**
 * The gateway response, either the server-to-server callback (silent URL) or
 * the success/fail redirect, which carries the same fields.
 */
export type Response = {
  amount: string;
  currency: Currency | string;
  invoiceId: string;
  epId: string;
  merchantId: string;
  action: string;
  message: string;
  approval: string;
  timestamp: string;
  nonce: string;
  fpHash: string;
} & AdditionalResponse;

/**
 * Optional response fields, enabled per MID in the EuPlătesc panel.
 *
 * Only the fields actually enabled are sent by the gateway, and they take part
 * in the `fp_hash` computation, appended after `nonce` in the order below. Pass
 * them exactly as received - omit the ones the gateway did not send.
 *
 * @since 1.1.0
 */
export type AdditionalResponse = {
  /** Additional security info. */
  secStatus?: string;
  /** Code generated by the bank, shown on the customer's bank statement. */
  rrn?: string;
  /** Last 4 digits of the used card. */
  mcard?: string;
  /** Expiration date of the used card, format: YYmm. */
  cardExp?: string;
  /** Applied discount. */
  discountAmount?: string;
  /** CARD, GPay, ApplePay, C2P, OP, SMS, TBI. */
  paymentChannel?: string;
  /** Visa, Mastercard, Maestro. */
  cardType?: string;
  /** First 6 digits of the used card. */
  bin?: string;
  /** Installments number. Format: `X rate BANK`, ex: `6 rate BTRL`. */
  rate?: string;
  /** Name on the used card. */
  cardHolder?: string;
  /** Email of the customer. */
  email?: string;
  /** Transaction type: Normal, Base, Recurent. */
  rtype?: string;
  /** Unique ID of the PAN. */
  cce?: string;
};

export type ResponseResult = {
  success: boolean;
  response: 'complete' | 'failed' | 'invalid';
};
